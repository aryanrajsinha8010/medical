def expand_and_rebuild():
    payload = build_raw_sources_and_rates()
    payload["canonical_terms"].extend(ADDITIONAL_TERMS)
    payload["rate_items"].extend(ADDITIONAL_RATES)
    payload["drug_prices"].extend(ADDITIONAL_DRUGS)

    manifest_path = RAW_DIR / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {"portal_probes": []}

    file_hashes = {}
    for key, records in payload.items():
        raw_file = RAW_DIR / f"{key}.json"
        raw_bytes = json.dumps(records, indent=2, ensure_ascii=False).encode("utf-8")
        raw_file.write_bytes(raw_bytes)
        file_hashes[f"data/raw/{key}.json"] = {
            "sha256": sha256_bytes(raw_bytes),
            "row_count": len(records),
            "bytes": len(raw_bytes),
            "generated_at": RETRIEVAL_DATE
        }

    manifest["raw_files"] = file_hashes
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")

    from run_etl import run_etl
    q = run_etl()
    print(f"[Expanded Dataset] Terms={q['row_counts']['canonical_term']}, Rates={q['row_counts']['rate_item']}, Drugs={q['row_counts']['drug_price']}")


